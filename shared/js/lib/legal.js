/** 文書の先頭の段落（leads）の後ろに出す、更新日の1行。 */
export function updatedLine() {
  return '更新日：' + UPDATED.label;
}

/** 文字列を、連絡先のメールアドレスで区切る。[{ text }, { mail: アドレス }, …]。画面も単独ページも、これでリンクにする。 */
export function splitContact(text) {
  const out = [];
  let rest = String(text);
  for (;;) {
    const i = rest.indexOf(CONTACT);
    if (i < 0) break;
    if (i > 0) out.push({ text: rest.slice(0, i) });
    out.push({ mail: CONTACT });
    rest = rest.slice(i + CONTACT.length);
  }
  if (rest || !out.length) out.push({ text: rest });
  return out;
}

/** 文書の全文を、段落ごとに1行の文字列にしたもの（テスト・検査用。画面には使わない）。 */
export function plainText(kind) {
  const d = DOCS[kind];
  const lines = [d.title, ...d.lead, updatedLine()];
  for (const s of d.sections) {
    lines.push(s.title);
    for (const b of s.blocks) {
      if (typeof b === 'string') lines.push(b);
      else if (b.ul) lines.push(...b.ul);
      else if (b.links) lines.push(...b.links.map((l) => l.text));
    }
  }
  return lines.join('\n');
}

